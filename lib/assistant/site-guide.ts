export function siteGuideText(): string {
  const sections = SITE_SECTIONS.map((section) => `- ${section.title} — ${section.path}: ${section.description}`).join("\n");
  const facts = PLATFORM_FACTS.map((fact) => `- ${fact}`).join("\n");
  return `## Разделы сайта\n${sections}\n\n## Факты о платформе\n${facts}`;
}
